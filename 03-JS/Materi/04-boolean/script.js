// 1. Deklarasi Boolean
// Boolean biasanya digunakan untuk menampung status "Ya/Tidak".
let isLampuNyala = true;
console.log("Apakah lampu nyala?", isLampuNyala);

// TUGAS 1: Buat variabel 'isLoggedIn' dengan nilai true.
// (Ketik di bawah)
let isLoggedIn = true;
console.log("apakah kamu sudh login?", isLoggedIn);

// 2. Mengubah Nilai Boolean
// TUGAS 2: Bayangkan user baru saja logout, ubah 'isLoggedIn' menjadi false.
// (Ketik di bawah)
isLoggedIn = false;
console.log("apakah kamu sudah login", isLoggedIn);

// 3. Nama Variabel Boolean
// Tips: Biasanya variabel boolean diawali dengan kata 'is', 'has', atau 'can'
// biar enak dibaca seperti pertanyaan.
// Contoh: isRed, hasMoney, canRun.

// TUGAS 3: Buat variabel boolean versimu sendiri menggunakan tips di atas.
// (Ketik di bawah)
let isClear = true;
console.log("apakah cuaca cerah?", isClear);

// 4. Cek Tipe Data
// TUGAS 4: Gunakan typeof untuk mengecek variabel yang kamu buat di Tugas 3.
// (Ketik di bawah)
console.log("Tipe data isClear:", typeof isClear);
