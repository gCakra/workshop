// 1. Aritmatika Dasar
// Coba hitung: (10 + 5) * 2 / 3
// (Ketik di bawah)
console.log(((10 + 5) * 2) / 3);

// 2. Modulo (%) -> Sisa Bagi
// Analogi: Kamu punya 10 permen, dibagikan ke 3 orang. Sisa berapa?
// Coba hitung: 10 % 3
// (Ketik di bawah)
console.log(10 % 3);

// 3. Eksponensial (Pangkat) -> **
// Coba hitung: 2 pangkat 3
// (Ketik di bawah)
console.log(2 ** 3);

// 4. Fenomena NaN (Not a Number)
// Terjadi kalau kamu melakukan operasi matematika pada data yang bukan angka.
// Coba bagi "Hello" dengan 2:
// (Ketik di bawah)
console.log("Hello" / 2);

// 5. Cek tipe data NaN pakai typeof
// console.log(typeof NaN);
// Tebak hasilnya apa sebelum dijalankan!
console.log(typeof NaN);
